// ─── Scheme comparison helper ───
export function compareSchemes(schemeIds) {
  return governmentSchemes.filter((s) => schemeIds.includes(s.id));
}

// ─── Get scheme by ID ───
export function getSchemeById(id) {
  return governmentSchemes.find((s) => s.id === id);
}

// ─── Filter by risk level ───
export function getSchemesByRisk(riskLevel) {
  return governmentSchemes.filter((s) => s.riskLevel === riskLevel);
}

// ─── Tax saving schemes (Section 80C) ───
export function getTaxSavingSchemes() {
  return governmentSchemes.filter((s) => s.section.includes('80C'));
}

